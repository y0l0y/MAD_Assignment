/* sign in / create account, opened on demand (guests can browse without it) */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AuthScreen(
    vm: BookViewModel,
    onNavigateBack: () -> Unit
) {
    var isSignUp by rememberSaveable { mutableStateOf(false) }
    var name by rememberSaveable { mutableStateOf("") }
    var email by rememberSaveable { mutableStateOf("") }
    var password by rememberSaveable { mutableStateOf("") }

    LaunchedEffect(Unit) { vm.clearAuthError() }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text(if (isSignUp) "Create account" else "Sign in") },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(
                            imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = "Back"
                        )
                    }
                }
            )
        }
    ) { paddingValues ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
                .padding(16.dp)
                .verticalScroll(rememberScrollState()),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            if (isSignUp) {
                OutlinedTextField(
                    value = name,
                    onValueChange = { name = it },
                    label = { Text("Full name") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
            }
            OutlinedTextField(
                value = email,
                onValueChange = { email = it },
                label = { Text("Email") },
                singleLine = true,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
                modifier = Modifier.fillMaxWidth()
            )
            OutlinedTextField(
                value = password,
                onValueChange = { password = it },
                label = { Text("Password") },
                singleLine = true,
                visualTransformation = PasswordVisualTransformation(),
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                modifier = Modifier.fillMaxWidth()
            )
            vm.authError?.let {
                Text(text = it, color = MaterialTheme.colorScheme.error)
            }
            Button(
                onClick = {
                    if (isSignUp) vm.signUp(name, email, password, onNavigateBack)
                    else vm.signIn(email, password, onNavigateBack)
                },
                enabled = !vm.authBusy,
                modifier = Modifier.fillMaxWidth()
            ) {
                if (vm.authBusy) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(20.dp),
                        strokeWidth = 2.dp
                    )
                } else {
                    Text(if (isSignUp) "Create account" else "Sign in")
                }
            }
            TextButton(
                onClick = {
                    isSignUp = !isSignUp
                    vm.clearAuthError()
                },
                modifier = Modifier.fillMaxWidth()
            ) {
                Text(if (isSignUp) "Already have an account? Sign in" else "No account? Create one")
            }
        }
    }
}
